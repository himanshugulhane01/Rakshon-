from sqlalchemy import Column, Integer, String, Boolean, Enum, ForeignKey, DateTime
import enum
from datetime import datetime, timezone
from app.core.database import Base
from app.models.base import TimestampMixin


class CircleConsentStatus(str, enum.Enum):
    PENDING = "PENDING"      # Pairing code generated, waiting for verification
    ACTIVE = "ACTIVE"        # Explicit consent verified and active
    REVOKED = "REVOKED"      # Consent revoked by senior or caregiver


class FamilyCircle(Base, TimestampMixin):
    __tablename__ = "family_circles"

    id = Column(Integer, primary_key=True, index=True)
    senior_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    caregiver_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=True, index=True)
    
    # 6-Digit ephemeral pairing code generated by the senior citizen
    consent_code = Column(String(6), nullable=False, index=True)
    consent_code_expires_at = Column(DateTime(timezone=True), nullable=False)
    
    status = Column(Enum(CircleConsentStatus), default=CircleConsentStatus.PENDING, nullable=False, index=True)
    relationship_label = Column(String(50), nullable=True)  # e.g., "Son", "Daughter", "Cousin"
    
    # Strict privacy safeguard: Caregivers only receive high-level alert metadata (e.g. "Risk Event: Power bill scam attempt blocked")
    # NEVER message body, NEVER OTPs, NEVER PINs, NEVER banking details.
    strict_privacy_enforced = Column(Boolean, default=True, nullable=False)
    
    consent_granted_at = Column(DateTime(timezone=True), nullable=True)
    consent_revoked_at = Column(DateTime(timezone=True), nullable=True)

